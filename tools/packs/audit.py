#!/usr/bin/env python3
"""Package audit (docs/PACKAGES.md section 2): where every catalog recipe, atom, rack, feel and groove entry actually comes from, whether it has a
namespaced id (author/pack:item), version and licence, and which entries are orphans (outside every pack manifest).
    python3 tools/packs/audit.py [--json] [--write-doc] [--check]      --write-doc rewrites the generated block of docs/PACKAGES.md; --check exits 1 when that block is stale
"""
import json, re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
def rd(p): return json.loads((ROOT / p).read_text())
def full_recipes():
    """index rows with their lazy body merged in (#131/#166: origin, intent and measurements live in data/recipes/<family>.json)"""
    out = []; files = {}
    for r in rd("site/data/catalog.json")["recipes"]:
        b = r.get("body")
        if b:
            if b not in files: files[b] = rd("site/data/recipes/" + b.replace("bodies-", "") + ".json")["bodies"]
            r = {**r, **files[b].get(r["id"], {})}
        out.append(r)
    return out
def pack_rows():
    rows = []
    extra = [(f"site/data/{d.name}/craftpack.json", f"site/data/{d.name}") for d in sorted((ROOT / "site/data").iterdir()) if (d / "craftpack.json").exists() and d.name not in ("phonk", "vox")]
    for mf, base in (("site/craftpack.json", "site"), ("site/data/phonk/craftpack.json", "site/data/phonk"), ("site/data/vox/craftpack.json", "site/data/vox"), *extra):
        m = rd(mf)
        for ing in m["ingredients"]:
            rows.append(dict(pack=m["id"], version=m["version"], license=m["license"], ing=ing["id"], kind=ing["kind"], iver=ing["version"], path=f"{base}/{ing['path']}"))
    return rows
def main():
    rows = pack_rows(); out = {"rows": []}
    def add(cls, source, n, pack, orphan, note, tagged=0, foldered=0):
        r = next((x for x in rows if x["pack"] == pack), None) if pack else None
        out["rows"].append(dict(cls=cls, source=source, n=n, pack=pack, version=r["version"] if r else None, license=r["license"] if r else None, orphan=orphan, note=note, tagged=tagged, foldered=foldered))
    cat = full_recipes()
    byorigin = {}
    for r in cat: byorigin.setdefault(r.get("origin", "?"), []).append(r)
    for o, l in byorigin.items():
        add("recipe", f"site/data/catalog.json origin={o}", len(l), "glyphcore/shim", False,
            "generated by tools/concepts/build.mjs from tools/concepts/families" if o == "concepts" else "hand-written (RECIPES.md / build_catalog.py)", sum(1 for r in l if r.get("tags")), sum(1 for r in l if r.get("folder")))
    ph = "site/data/phonk"
    def cnt(f, key):
        d = rd(f"{ph}/{f}"); it = d[key]; it = list(it.values()) if isinstance(it, dict) else it; return len(it), sum(1 for x in it if x.get("tags")), sum(1 for x in it if x.get("folder"))
    for f, cls, note in (("presets.json", "recipe", "night phonk tracks"), ("atoms.json", "atom", "hand-written ph."), ("atoms-v2.json", "atom", "hand-written ph2."),
                         ("atoms-hiphop.json", "atom", "generated hh."), ("atoms-dovetail.json", "atom", "generated dt.")):
        n, t, fo = cnt(f, "recipes" if cls == "recipe" else "atoms"); add(cls, f"{ph}/{f}", n, "glyphcore/phonk", False, note, t, fo)
    for i in ("boombap", "lazy", "trap", "hyphy", "cloud"):
        n, t, fo = cnt(f"feel-{i}.json", "atoms"); add("feel", f"{ph}/feel-{i}.json", n, "glyphcore/phonk", False, "generated feel template slots", t, fo)
    for f, note in (("racks.json", "hand-written racks"), ("racks-v2.json", "hand-written racks"), ("racks-hiphop.json", "generated racks and dovetail moves"), ("grooves.json", "groove presets (copy of site/engine/groove.js GROOVES; the engine keeps the standard library)")):
        n, t, fo = cnt(f, "defs"); add("rack" if "groove" not in f else "groove", f"{ph}/{f}", n, "glyphcore/phonk", False, note, t, fo)
    # every other content pack under site/data (glyphcore/edm, ...): one row per atoms / hooks ingredient, read from its manifest
    for row in rows:
        if row["pack"] in ("glyphcore/shim", "glyphcore/phonk", "glyphcore/vox") or row["kind"] not in ("atoms", "hooks"): continue
        d = rd(row["path"]); it = d["atoms"] if row["kind"] == "atoms" else d["defs"]; it = list(it.values())
        cls = "feel" if row["ing"].startswith("feel-") else "atom" if row["kind"] == "atoms" else "rack"
        add(cls, row["path"], len(it), row["pack"], False, "generated by tools/concepts/build.mjs", sum(1 for x in it if x.get("tags")), sum(1 for x in it if x.get("folder")))
    g = len(re.findall(r"^  'groove-", (ROOT / "site/engine/groove.js").read_text(), re.M))
    add("groove", "site/engine/groove.js GROOVES (standard library)", g, None, False, "engine built-in, kept for --no-packs; every def is also in glyphcore/phonk:grooves (parity tested)")
    pp = len(rd("site/data/perform/presets.json")["presets"])
    add("perform preset", "site/data/perform/presets.json", pp, None, True, "pack kind perform-presets is coming (PACK_SPEC 5); no adapter yet")
    ws = (ROOT / "site/workspace.js").read_text(); blk = ws[ws.index("const DEFAULTS = {"):ws.index("let rows = []")]; lay = len(re.findall(r"^  (?:'[^']+'|[A-Z]\w*): \{ rows:", blk, re.M))
    add("layout", "site/workspace.js DEFAULTS", lay, None, True, "kind layouts has an adapter; content moves with P4 (#69)")
    syn = rd("site/data/syntax.json"); add("syntax example", "site/data/syntax.json", sum(len(s["examples"]) for s in syn["sections"]), "glyphcore/shim", False, "kind syntax")
    add("control type", "site/data/controls/types.json", len(rd("site/data/controls/types.json")["types"]), "glyphcore/shim", False, "kind control-types")
    out["total_entries"] = sum(r["n"] for r in out["rows"]); out["orphans"] = sum(r["n"] for r in out["rows"] if r["orphan"])
    out["in_provisional_shim"] = sum(r["n"] for r in out["rows"] if r["pack"] == "glyphcore/shim")
    out["in_real_pack"] = sum(r["n"] for r in out["rows"] if r["pack"] == "glyphcore/phonk")
    out["in_other_packs"] = sum(r["n"] for r in out["rows"] if r["pack"] not in (None, "glyphcore/phonk", "glyphcore/shim"))
    out["engine_builtin"] = sum(r["n"] for r in out["rows"] if r["pack"] is None and not r["orphan"])
    out["tagged"] = sum(r["tagged"] for r in out["rows"]); out["foldered"] = sum(r["foldered"] for r in out["rows"])
    return out
def table(o):
    L = ["| class | entries | source | pack (namespaced ids) | pack version | licence | orphan | folder | tags | note |", "|---|---|---|---|---|---|---|---|---|---|"]
    for r in o["rows"]:
        L.append(f"| {r['cls']} | {r['n']} | `{r['source']}` | {('`' + r['pack'] + '`') if r['pack'] else 'none'} | {r['version'] or '-'} | {r['license'] or '-'} | {'**yes**' if r['orphan'] else 'no'} | {r['foldered']} | {r['tagged']} | {r['note']} |")
    L += ["", f"Totals: {o['total_entries']} entries; {o['in_real_pack']} in the real pack `glyphcore/phonk` (CC0-1.0); {o['in_other_packs']} in other real packs under site/data (glyphcore/edm, ...; CC0-1.0); {o['in_provisional_shim']} in the provisional `glyphcore/shim` pack (licence undecided, #66; replaced by `glyphcore/core` in P4, #69); {o['engine_builtin']} engine built-ins (groove standard library, duplicated in `glyphcore/phonk:grooves`); **{o['orphans']} orphans** outside every pack; {o['foldered']} with a folder and {o['tagged']} with tags in the pack data."]
    return "\n".join(L)
if __name__ == "__main__":
    o = main()
    if "--json" in sys.argv: print(json.dumps(o, indent=1))
    else: print(table(o))
    if "--check" in sys.argv:
        m = re.search(r"<!-- audit:begin -->\n(.*?)\n<!-- audit:end -->", (ROOT / "docs" / "PACKAGES.md").read_text(), flags=re.S)
        if not m or m[1] != table(o): print("docs/PACKAGES.md audit table is stale: run python3 tools/packs/audit.py --write-doc"); sys.exit(1)
        print("audit table in docs/PACKAGES.md is current")
    if "--write-doc" in sys.argv:
        f = ROOT / "docs" / "PACKAGES.md"; t = f.read_text()
        t2 = re.sub(r"(<!-- audit:begin -->\n).*?(\n<!-- audit:end -->)", lambda m: m[1] + table(o) + m[2], t, flags=re.S)
        f.write_text(t2)
