#!/usr/bin/env python3
"""Generate site/taxonomy.css: colour tokens --tx-<key> (ink) and --tx-<key>-bg (tint) for the fixed palette, dark on :root and light overrides,
and fail when any pair is below WCAG AA 4.5:1 (ink on the panel surfaces, ink on its own tint). The test tests/site/taxonomy.mjs re-checks the file.
    python3 tools/packs/gen_taxonomy_css.py [--check]"""
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
DARK = {'amber': '#ffc247', 'orange': '#ff8a4c', 'red': '#ff7b7b', 'rose': '#ff8fb1', 'violet': '#b9a0ff', 'indigo': '#9fb0ff', 'blue': '#7cc0ff', 'cyan': '#4fdcf0', 'teal': '#3fe0c8', 'green': '#6ee787', 'lime': '#b8e84a', 'slate': '#aab4c0'}
LIGHT = {'amber': '#7a4d00', 'orange': '#a63d00', 'red': '#b3261e', 'rose': '#a8235a', 'violet': '#5b3fc4', 'indigo': '#3a4fc0', 'blue': '#0b5fb0', 'cyan': '#00697a', 'teal': '#0f6f64', 'green': '#176a3b', 'lime': '#4a6a00', 'slate': '#46505b'}
SURF = {'dark': ['#12161b', '#181d24', '#1f252e'], 'light': ['#fbfaf7', '#f3f1ec', '#e8e5de']}  # --panel, --panel-2, --panel-3 of style.css
def rgb(h): return [int(h[i:i+2], 16) for i in (1, 3, 5)]
def mix(a, b, t): return '#%02x%02x%02x' % tuple(round(x * t + y * (1 - t)) for x, y in zip(rgb(a), rgb(b)))
def lum(h):
    c = [x / 255 for x in rgb(h)]; c = [x / 12.92 if x <= .03928 else ((x + .055) / 1.055) ** 2.4 for x in c]; return .2126 * c[0] + .7152 * c[1] + .0722 * c[2]
def ratio(a, b): la, lb = sorted((lum(a), lum(b)), reverse=True); return (la + .05) / (lb + .05)
def build():
    out = ['/* generated by tools/packs/gen_taxonomy_css.py: the fixed accessible palette of site/engine/taxonomy.js PALETTE (ink and tint per key, dark default, light override) */']
    bad = []
    for theme, ink in (('dark', DARK), ('light', LIGHT)):
        sel = ':root' if theme == 'dark' else ':root[data-theme="light"]'
        rows = []
        for k, c in ink.items():
            bg = mix(c, SURF[theme][0], .16 if theme == 'dark' else .12)
            for s in SURF[theme] + [bg]:
                if ratio(c, s) < 4.5: bad.append(f'{theme} {k} {c} on {s}: {ratio(c, s):.2f}')
            # tinted rows sit on panel-3 when selected: the tint is always against its own ink
            rows.append(f'--tx-{k}:{c};--tx-{k}-bg:{bg}')
        out.append(sel + '{' + ';'.join(rows) + '}')
    return '\n'.join(out) + '\n', bad
if __name__ == '__main__':
    css, bad = build()
    if bad: print('\n'.join(bad)); sys.exit(1)
    f = ROOT / 'site' / 'taxonomy.css'
    if '--check' in sys.argv: sys.exit(0 if f.exists() and f.read_text() == css else 1)
    f.write_text(css); print('wrote', f)
